"""Grounded Assistant (ADR-0006): answers questions about the study on screen, using only what the app
measured. Gemini (config.GEMINI_MODEL), key GEMINI_API_KEY in the environment or .env. Status: prototype.

Its context is the current manifest (layers, Passes, quality notes, insights), the statistics of the
layer and date on screen, and the Model card when the study is a Showcase Site. It has no tools and
cannot move the map. Answers are labelled as AI-generated by the API and the frontend.
"""
from __future__ import annotations

import json

from saraura import config

LANGUAGES = {"en": "English", "fr": "French", "ar": "Arabic", "es": "Spanish"}

RULES = """You are the Assistant inside SARAURA, an app that shows how Earth's surface changes using NASA-ISRO NISAR L-band radar.

You answer questions about ONE study (a Showcase Site or a user's Analysis). Everything you know about it is in the CONTEXT below.

Rules:
- Use only numbers, dates and areas that appear in the CONTEXT. Never invent or estimate a number. If the answer is not in the CONTEXT, say so and suggest which layer or chart would show it.
- Radar shows that something changed, not why. Give the likely cause as a hypothesis and say what would confirm it (optical images, field reports, official maps).
- When you mention an AI Model's result, also give its Baseline score and its limits from the Model card. Never present a Model as better than its Baseline unless the card's scores say so.
- Say "line of sight" for displacement; it is not purely vertical.
- Radar basics you may use: HH and HV are two polarisations in decibels (dB). HV is strongest over vegetation volume (forest, tall crops). Calm open water is dark in both. Buildings are bright in HH. Coherence (0 to 1) is how similar the ground looked between two Passes; it drops where the surface was disturbed.
- Write for a curious non-expert: short sentences, explain any technical word. Under 150 words unless asked for more."""


class Unavailable(RuntimeError):
    pass


def key() -> str:
    return config.secret("GEMINI_API_KEY")


def info() -> dict:
    try:
        from google import genai  # noqa: F401

        installed = True
    except ImportError:
        installed = False
    return {"configured": bool(key()) and installed, "sdk_installed": installed, "key_present": bool(key()), "model": config.GEMINI_MODEL, "status": "prototype"}


def context(m: dict, layer_stats: dict | None = None, card: dict | None = None) -> str:
    """The grounding text: only what the app computed for this study."""
    doc = {
        "study": {"kind": m["kind"], "name": m.get("name"), "lens": m.get("lens"), "bbox": m["bbox"], "event_date": m.get("event_date")},
        "passes": {"count": len(m["passes"]), "first": m["passes"][0]["date"], "last": m["passes"][-1]["date"],
                   "stacks": sorted({p["stack"] for p in m["passes"]}), "collections": sorted({p["collection"] for p in m["passes"]})},
        "layers": [{"id": l["id"], "label": l["label"], "kind": l["kind"], "unit": l["unit"], "status": l["status"], "what_this_shows": l.get("what_this_shows"),
                    "dates": [l["dates"][0], l["dates"][-1]] if len(l["dates"]) > 2 else l["dates"]} for l in m["layers"]],
        "insights": m.get("insights", []),
        "quality": m.get("quality", {}),
    }
    if layer_stats:
        doc["on_screen"] = layer_stats
    if card and m["kind"] == "showcase":
        doc["model_card"] = {k: card.get(k) for k in ("job", "labels", "baseline", "model", "extra_scores", "split", "limits", "status")}
    return json.dumps(doc, ensure_ascii=False, indent=1)


def _client():
    if not key():
        raise Unavailable("The Assistant is not set up: add GEMINI_API_KEY to the .env file and restart the API.")
    try:
        from google import genai
    except ImportError:
        raise Unavailable("The Assistant needs the google-genai package: pip install google-genai")
    return genai.Client(api_key=key())


def ask(question: str, m: dict, layer_stats: dict | None = None, card: dict | None = None, language: str = "en", client=None) -> str:
    from google.genai import types

    client = client or _client()
    system = RULES + f"\n\nAnswer in {LANGUAGES.get(language, 'English')}.\n\nCONTEXT:\n" + context(m, layer_stats, card)
    resp = client.models.generate_content(
        model=config.GEMINI_MODEL,
        contents=question,
        # Gemini 3 models think before answering, and thinking counts against max_output_tokens: a small cap
        # cut answers off mid-sentence. Low thinking keeps answers fast; the length rule is in the prompt.
        config=types.GenerateContentConfig(system_instruction=system, temperature=0.2, max_output_tokens=4096,
                                           thinking_config=types.ThinkingConfig(thinking_level="low")),
    )
    text = (resp.text or "").strip()
    if not text:
        raise RuntimeError("The model returned no text")
    candidates = getattr(resp, "candidates", None) or []
    reason = str(getattr(candidates[0], "finish_reason", "")) if candidates else ""
    if "MAX_TOKENS" in reason:
        text += " [answer cut off: ask a narrower question]"
    return text
